#!/usr/bin/env node
/**
 * Pick the game-icons.net glyphs we use (CC BY 3.0, https://game-icons.net — attribution in CREDITS) out of
 * @iconify-json/game-icons and write them into a small TS module, so the bundle only carries ~60 icons.
 *   node tools/icons/build.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/game-icons/icons.json');
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

/** item id or `cat:<category>` → game-icons name */
export const ICONS = {
  // ammo
  a_12buck: 'shotgun-rounds', a_12slug: 'shotgun-rounds', a_9x18: 'bullets', a_9x19: 'bullets', a_9x19ap: 'bullets',
  'cat:ammo': 'heavy-bullets',
  // armour / helmets / rigs / bags / secure
  paca: 'leather-vest', '6b23': 'kevlar-vest', trooper: 'kevlar-vest', gzhel: 'armor-vest', slick6: 'armor-vest',
  ssh68: 'brodie-helmet', zsh: 'helmet', altyn: 'closed-barbute',
  'cat:rig': 'belt-armor', r_scav: 'leather-vest',
  b_sling: 'knapsack', b_daypack: 'light-backpack', 'cat:backpack': 'backpack',
  'cat:secure': 'locked-chest',
  // meds
  bandage: 'bandage-roll', esmarch: 'arm-bandage', splint: 'broken-bone', ai2: 'first-aid-kit', salewa: 'first-aid-kit',
  ifak: 'medical-pack', grizzly: 'medical-pack-alt', cms: 'scalpel', surv12: 'stitched-wound', analgin: 'medicine-pills',
  morphine: 'syringe', stim: 'health-capsule',
  // food & drink
  water: 'water-bottle', juice: 'soda-bottle', crackers: 'bread-slice', mre: 'hot-meal', tushonka: 'canned-fish',
  // valuables
  bitcoin: 'coins', chain: 'gem-necklace', cpu: 'processor', flash: 'usb-key', gpu: 'circuitry', intel: 'files', ledx: 'microscope',
  lion: 'lion', rolex: 'pocket-watch',
  // junk
  battery: 'car-battery', bolts: 'screw', tank: 'fuel-tank', tools: 'toolbox', wires: 'wire-coil',
  roubles: 'money-stack',
  // weapon mods
  sup_9: 'straight-pipe', sup_545: 'straight-pipe', sup_556: 'straight-pipe', sup_762: 'straight-pipe', sup_54r: 'straight-pipe', brake: 'reload-gun-barrel',
  red_dot: 'crosshair', holo: 'crosshair', scope_4x: 'telescope', scope_8x: 'telescope', fgrip: 'hand-grip', stock_tac: 'gun-stock',
  tac_light: 'flashlight', 'cat:mod': 'machine-gun-magazine',
  // fallbacks for guns/melee when no 3D thumbnail is ready yet
  'cat:weapon': 'pistol-gun', 'cat:melee': 'bowie-knife', 'cat:med': 'first-aid-kit', 'cat:food': 'meal', 'cat:drink': 'water-bottle',
  'cat:valuable': 'gems', 'cat:junk': 'cog', 'cat:money': 'money-stack', 'cat:armor': 'kevlar-vest', 'cat:helmet': 'helmet',
};

const out = {};
const missing = [];
for (const name of new Set(Object.values(ICONS))) {
  const ic = set.icons[name];
  if (!ic) missing.push(name);
  else out[name] = ic.body;
}
if (missing.length) throw new Error(`missing icons: ${missing.join(', ')}`);
const file = path.join(ROOT, 'apps/web/src/ui/inventory/gameIcons.ts');
fs.writeFileSync(
  file,
  `// Generated by tools/icons/build.mjs — game-icons.net (CC BY 3.0, Lorc, Delapouite & contributors). Do not edit.\n` +
    `export const ICON_FOR: Record<string, string> = ${JSON.stringify(ICONS, null, 1)};\n` +
    `/** SVG inner markup on a ${set.width ?? 512}×${set.height ?? 512} viewBox. */\n` +
    `export const ICON_BODY: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`wrote ${Object.keys(out).length} icons → ${path.relative(ROOT, file)} (${(fs.statSync(file).size / 1024).toFixed(1)} KB)`);
